/// 超过这个距离就不认了：附近确实没有表里的城市时，宁可不填，
/// 也别把几百公里外的城市硬安上去。
const MAX_DISTANCE_KM: f64 = 120.0;

const EARTH_RADIUS_KM: f64 = 6371.0;

fn distance_km(lat1: f64, lon1: f64, lat2: f64, lon2: f64) -> f64 {
    let (phi1, phi2) = (lat1.to_radians(), lat2.to_radians());
    let delta_phi = (lat2 - lat1).to_radians() / 2.0;
    let delta_lambda = (lon2 - lon1).to_radians() / 2.0;
    let a = delta_phi.sin().powi(2) + phi1.cos() * phi2.cos() * delta_lambda.sin().powi(2);
    2.0 * EARTH_RADIUS_KM * a.sqrt().clamp(-1.0, 1.0).asin()
}

/// 坐标落在哪个市。附近没有表内城市时返回 None，交给用户自己填。
pub fn nearest_city(latitude: f64, longitude: f64) -> Option<&'static str> {
    let mut best: Option<(&'static str, f64)> = None;
    for (name, lat, lon) in CITIES {
        let distance = distance_km(latitude, longitude, *lat, *lon);
        if best.map_or(true, |(_, current)| distance < current) {
            best = Some((name, distance));
        }
    }
    best.filter(|(_, distance)| *distance <= MAX_DISTANCE_KM)
        .map(|(name, _)| name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_the_city_around() {
        // 西湖
        assert_eq!(nearest_city(30.2596, 120.1478), Some("杭州"));
        // 天安门
        assert_eq!(nearest_city(39.9087, 116.3975), Some("北京"));
        // 外滩
        assert_eq!(nearest_city(31.2397, 121.4900), Some("上海"));
    }

    #[test]
    fn refuses_when_too_far() {
        // 太平洋正中
        assert_eq!(nearest_city(0.0, -150.0), None);
        // 藏北无人区：离最近的拉萨也远超上限
        assert_eq!(nearest_city(35.0, 88.0), None);
    }
}
